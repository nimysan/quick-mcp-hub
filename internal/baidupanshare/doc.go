// Package baidupanshare 读百度网盘的「公开分享链接」：给一个链接和提取码，
// 列出里面有哪些文件和目录。只读，不碰使用者自己的网盘，也不需要任何账号。
//
// 和 catalog/baidupan.json 那条渠道的区别：那条走开放平台 OpenAPI，以使用者
// 本人的身份操作**他自己的**网盘；这里走网页版的匿名分享接口，读的是**别人
// 分享出来的**链接。两件不同的事，所以是两条渠道。
//
// # 为什么不能做成一份声明
//
// 声明引擎的 auth.kind 只有 bearer / header / basic / query / login，而 login
// 是「账号 + 密码换会话」的固定形状。这里要的是：先取一次页面拿 cookie 和两个
// id，再 POST 提取码换一个新 cookie，之后每次列目录都带着它 —— 表达不出来。
//
// # 接口形状（2026-11-23 实测，不是照文档写的）
//
// 这些接口百度没有公开文档，下面每一条都是对着真实链接跑出来的：
//
//	① GET  /s/1<surl>                 302 到 /share/init?surl=<surl>
//	                                  下发 BAIDUID、BAIDUID_BFESS、csrfToken
//	                                  init 页的 HTML 里直接带 shareid 和 share_uk，
//	                                  不需要额外接口去查
//	② POST /share/verify?surl=<surl>   form: pwd=<提取码>&vcode=&vcode_str=
//	                                  errno 0 时下发 BDCLND，这才是会话凭据
//	③ GET  /share/list?uk=&shareid=…   根目录必须 root=1；子目录用 dir=<完整路径>
//
// 几个只有实测才会发现的坑，写在这里省得下一个人再踩：
//
//   - 链接里的 id 是 "1" + surl，参数要的是去掉那个 "1" 的部分。
//   - 列根目录用 dir=/ 不是「空结果」，是 errno 2。必须用 root=1。
//   - isdir 和 size 回的是字符串（"1"、"0"），不是数字；但有些字段又是数字，
//     所以用 flexInt 两种都认。
//   - 不带 Referer 会被拒，所以每个请求都带上对应的页面地址。
//   - 一页最多 num=100 条，满 100 就要继续翻页，否则会静悄悄地只看到前 100 个。
//
// # 错误码
//
//	 0   成功
//	-9   提取码错了（长度对、内容不对）
//	-12  提取码格式不对（空的、长度不对）
//	 2   dir 参数不对（最常见的原因是拿 dir=/ 列根目录）
//	-62  被限频
//
// -9 和 -12 是实测的。-62 没有实测：触发它要对同一个出口 IP 连续猛打，代价落在
// 使用者自己的网络上（限频按请求方算，不是记在分享链接上），不值得为了确认一个
// 常量去换。所以这里的处理方式刻意不依赖精确阈值：认出 -62、退避、有总上限、
// 退不动就把「被限频了，过几分钟再试」如实报出去。
